<script setup>
// 1. 导入Vue核心API：ref用于创建响应式变量，watch用于监听数据变化
import {ref, watch} from 'vue'
// 2. 导入Vue Router核心API：useRouter用于路由跳转，useRoute用于获取当前路由信息
import {useRouter, useRoute} from 'vue-router'

// 3. 初始化路由实例，用于编程式导航（如push跳转页面）
const router = useRouter()
// 4. 初始化当前路由对象，用于获取当前路由的name、path等信息
const route = useRoute()

// 5. 定义退出登录处理函数
const handleLogout = () => {
  // 6. 弹出确认框，确认用户是否真的要退出（原生JS确认框）
  if (confirm('确定退出吗？')) {
    // 7. 清除本地存储中的登录状态标识，实现登录状态重置
    localStorage.removeItem('isLogin')
    // 8. 跳转到登录页面（通过路由name或path跳转）
    router.push('/login')
  }
}

// 9. 创建响应式变量activeNav，用于标识当前激活的导航项，初始值为当前路由的name
const activeNav = ref(route.name)
// 10. 监听路由name的变化，实现导航激活状态自动同步
watch(
    // 10.1 监听的目标：当前路由的name属性
    () => route.name,
    // 10.2 回调函数：路由name变化时，更新activeNav的值
    (newName) => {
      activeNav.value = newName
    },
    // 10.3 配置项：immediate: true 表示立即执行一次监听回调（页面初始化时同步状态）
    {immediate: true}
)

// 11. 定义通用的页面跳转函数，接收页面名称（路由name）作为参数
const goToPage = (pageName) => {
  // 11.1 通过路由name跳转到指定页面（推荐使用name跳转，比path更稳定）
  console.log("111",pageName);
  router.push({name: pageName})
}
</script>

